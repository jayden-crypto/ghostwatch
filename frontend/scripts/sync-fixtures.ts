/**
 * Copies contract/fixtures/*.json into mocks/fixtures/ and writes mocks/fixtures/index.ts, the
 * typed module the mock adapter imports.
 *
 *   npm run sync-fixtures      (also runs before dev, build, typecheck, lint and test)
 *
 * mocks/fixtures/ is generated and git-ignored: contract/fixtures/ is the only source.
 */
import { copyFileSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { typeFor } from "./fixture-types";

const FRONTEND = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(FRONTEND, "../contract/fixtures");
const TARGET = join(FRONTEND, "mocks/fixtures");

const files = readdirSync(SOURCE).filter((file) => file.endsWith(".json")).sort();
if (files.length === 0) {
  console.error(`No fixtures in ${SOURCE}. Pull main (the X1 fixtures) first.`);
  process.exit(1);
}

rmSync(TARGET, { recursive: true, force: true });
mkdirSync(TARGET, { recursive: true });

const imports: string[] = [];
const entries: string[] = [];
files.forEach((file, index) => {
  const type = typeFor(file);
  if (!type) {
    console.error(`${file}: no type is mapped to this name (scripts/fixture-types.ts).`);
    process.exit(1);
  }
  copyFileSync(join(SOURCE, file), join(TARGET, file));
  imports.push(`import f${index} from "./${file}";`);
  // A JSON import widens enum values to string; validate-fixtures is what proves the cast is sound.
  entries.push(`  ${JSON.stringify(file.replace(/\.json$/, ""))}: f${index} as unknown as T.${type},`);
});

writeFileSync(
  join(TARGET, "index.ts"),
  [
    "// Generated by scripts/sync-fixtures.ts from contract/fixtures/. Do not edit.",
    'import type * as T from "@/lib/api/types";',
    "",
    ...imports,
    "",
    "export const fixtures = {",
    ...entries,
    "};",
    "",
    "export type FixtureName = keyof typeof fixtures;",
    "",
  ].join("\n"),
);
console.log(`Synced ${files.length} fixtures to mocks/fixtures/`);
