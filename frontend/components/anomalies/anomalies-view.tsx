"use client";

/**
 * /anomalies: what the detection rules have flagged, most severe first. Each anomaly shows the
 * rule's own explanation and links to the exact steps in its evidence.
 *
 * Filters live in the URL under the contract's names for `GET /anomalies`: `status`, `severity`,
 * `agent_id`, `type`. With no `status` in the URL the view shows open anomalies, which is what
 * needs attention. `?anomaly=<id>` pins one anomaly to the top, whatever the filters say.
 */
import { SearchX, ShieldCheck, X } from "lucide-react";
import { useEffect, useRef } from "react";

import { SeverityBadge } from "@/components/data/badges";
import { ChipFilter } from "@/components/data/controls";
import { EmptyState } from "@/components/data/empty-state";
import { ErrorState, Refreshing } from "@/components/data/states";
import { Page } from "@/components/shell/page";
import { Button } from "@/components/ui/button";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Skeleton } from "@/components/ui/skeleton";
import { LIST_POLL_MS, useAgents, useAnomalies, useAnomaly } from "@/lib/api/hooks";
import { ANOMALY_STATUSES, ANOMALY_TYPES, SEVERITIES, type AnomalyStatus, type AnomalyType, type Severity } from "@/lib/api/types";
import { ANOMALY_STATUS, ANOMALY_TYPE, SEVERITY } from "@/lib/enums";
import { formatCount, pluralize } from "@/lib/format";
import { useUrlState } from "@/lib/use-url-state";

import { AnomalyCard } from "./anomaly-card";

const ANY = "any";
/** The contract's largest page. Beyond it the view says how many are not shown. */
const LIMIT = 200;
const MOST_SEVERE_FIRST = [...SEVERITIES].reverse();

const list = <T extends string>(value: string | null, allowed: readonly T[]): T[] =>
  (value ?? "").split(",").filter((item): item is T => (allowed as readonly string[]).includes(item));

const STATUS_OPTIONS = ANOMALY_STATUSES.map((status) => ({ value: status, label: ANOMALY_STATUS[status].label, tone: ANOMALY_STATUS[status].tone }));
const SEVERITY_OPTIONS = MOST_SEVERE_FIRST.map((severity) => ({ value: severity, label: SEVERITY[severity].label, tone: SEVERITY[severity].tone }));

export function AnomaliesView() {
  const [params, setParams] = useUrlState();
  const requestedStatus = list<AnomalyStatus>(params.get("status"), ANOMALY_STATUSES);
  const status: AnomalyStatus[] = requestedStatus.length ? requestedStatus : ["open"];
  const severity = list<Severity>(params.get("severity"), SEVERITIES);
  const agentId = params.get("agent_id");
  const typeParam = params.get("type");
  const type = (ANOMALY_TYPES as readonly string[]).includes(typeParam ?? "") ? (typeParam as AnomalyType) : null;
  const pinnedId = params.get("anomaly");
  const narrowed = severity.length > 0 || agentId !== null || type !== null || requestedStatus.length > 0;

  const agents = useAgents({ limit: 200 });
  const { data, error, refetch, isFetching, isPlaceholderData } = useAnomalies(
    { status, severity: severity.length ? severity : undefined, agent_id: agentId ?? undefined, type: type ?? undefined, limit: LIMIT },
    { refetchInterval: LIST_POLL_MS },
  );
  const pinned = useAnomaly(pinnedId);

  // A link to one anomaly lands on it.
  const pinnedRef = useRef<HTMLDivElement>(null);
  const pinnedLoaded = pinned.data?.id;
  useEffect(() => {
    if (pinnedLoaded) pinnedRef.current?.scrollIntoView({ block: "start" });
  }, [pinnedLoaded]);

  const clear = () => setParams({ status: null, severity: null, agent_id: null, type: null });
  const others = data?.items.filter((anomaly) => anomaly.id !== pinnedId);

  return (
    <Page
      title="Anomalies"
      description="Runs that broke a deterministic detection rule. Each one states the rule, its threshold and the recorded evidence; none of this is generated by a model."
      actions={
        <>
          <Refreshing active={isFetching && data !== undefined} />
          {data && <span className="num text-fg-muted">{pluralize(data.total, "anomaly", "anomalies")}</span>}
        </>
      }
    >
      <div className="flex flex-wrap items-center gap-x-3 gap-y-2 rounded-lg border border-line-subtle bg-surface px-4 py-3" role="search" aria-label="Filter anomalies">
        <ChipFilter label="Status" options={STATUS_OPTIONS} selected={status} onChange={(next) => setParams({ status: next.join(",") })} />
        <span aria-hidden="true" className="h-4 w-px bg-line" />
        <ChipFilter label="Severity" options={SEVERITY_OPTIONS} selected={severity} onChange={(next) => setParams({ severity: next.join(",") })} />
        <Select value={agentId ?? ANY} onValueChange={(next) => setParams({ agent_id: next === ANY ? null : next })}>
          <SelectTrigger size="sm" aria-label="Agent" className="h-7 min-w-40">
            <SelectValue />
          </SelectTrigger>
          <SelectContent>
            <SelectItem value={ANY}>Agent: any</SelectItem>
            {agents.data?.items.map((agent) => (
              <SelectItem key={agent.id} value={agent.id}>
                {agent.name}
              </SelectItem>
            ))}
            {agentId && !agents.data?.items.some((agent) => agent.id === agentId) && <SelectItem value={agentId}>{agentId}</SelectItem>}
          </SelectContent>
        </Select>
        <Select value={type ?? ANY} onValueChange={(next) => setParams({ type: next === ANY ? null : next })}>
          <SelectTrigger size="sm" aria-label="Rule" className="h-7 min-w-44">
            <SelectValue />
          </SelectTrigger>
          <SelectContent>
            <SelectItem value={ANY}>Rule: any</SelectItem>
            {ANOMALY_TYPES.map((value) => (
              <SelectItem key={value} value={value}>
                {ANOMALY_TYPE[value].label}
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
        {narrowed && (
          <Button variant="ghost" size="sm" onClick={clear} className="ml-auto text-fg-muted">
            <X aria-hidden="true" />
            Reset
          </Button>
        )}
      </div>

      {pinnedId && (
        <section ref={pinnedRef} aria-label="Linked anomaly" className="flex scroll-mt-4 flex-col gap-2">
          <div className="flex items-center justify-between">
            <h2 className="text-xs font-medium text-fg-subtle">Linked anomaly</h2>
            <Button variant="ghost" size="xs" onClick={() => setParams({ anomaly: null })} className="text-fg-muted">
              <X aria-hidden="true" />
              Unpin
            </Button>
          </div>
          {pinned.error ? (
            <ErrorState error={pinned.error} onRetry={() => void pinned.refetch()} title="The linked anomaly could not be loaded" compact className="rounded-lg border border-failed/30" />
          ) : pinned.data ? (
            <AnomalyCard anomaly={pinned.data} focused />
          ) : (
            <Skeleton className="h-32 w-full rounded-lg" />
          )}
        </section>
      )}

      {error ? (
        <ErrorState error={error} onRetry={() => void refetch()} title="Anomalies could not be loaded" />
      ) : !others ? (
        <div className="flex flex-col gap-3" aria-busy="true" aria-label="Loading anomalies">
          {Array.from({ length: 3 }, (_, index) => (
            <Skeleton key={index} className="h-32 w-full rounded-lg" />
          ))}
        </div>
      ) : others.length === 0 && !pinnedId ? (
        narrowed ? (
          <EmptyState
            icon={SearchX}
            title="No anomalies match these filters"
            description="Loosen or reset the filters to see more."
            action={
              <Button variant="outline" size="sm" onClick={clear}>
                Reset filters
              </Button>
            }
          />
        ) : (
          <EmptyState
            icon={ShieldCheck}
            title="No open anomalies"
            description="No run currently breaks a detection rule. The eight rules run on every execution as it ends; acknowledged and resolved anomalies are behind the Status filter."
          />
        )
      ) : (
        <div className={isPlaceholderData ? "flex flex-col gap-6 opacity-60" : "flex flex-col gap-6"}>
          {MOST_SEVERE_FIRST.map((level) => {
            const group = others.filter((anomaly) => anomaly.severity === level);
            if (group.length === 0) return null;
            return (
              <section key={level} aria-labelledby={`severity-${level}`} className="flex flex-col gap-2">
                <h2 id={`severity-${level}`} className="flex items-center gap-2 text-13 font-medium">
                  <SeverityBadge severity={level} />
                  <span className="num font-mono text-xs font-normal text-fg-subtle">{formatCount(group.length)}</span>
                </h2>
                {group.map((anomaly) => (
                  <AnomalyCard key={anomaly.id} anomaly={anomaly} defaultOpen={level === "critical"} />
                ))}
              </section>
            );
          })}
          {data && data.total > data.items.length && (
            <p className="text-xs text-fg-subtle">
              Showing the {formatCount(data.items.length)} most recent of {formatCount(data.total)}. Narrow the filters to see the rest.
            </p>
          )}
        </div>
      )}
    </Page>
  );
}
