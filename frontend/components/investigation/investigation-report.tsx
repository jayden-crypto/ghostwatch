"use client";

/**
 * An investigation report (contract §9), laid out so that what is known and what is supposed can
 * never be confused.
 *
 * - The root-cause banner has three treatments, one per `RootCauseStatus`.
 * - **Facts** were computed by backend code from recorded events. Solid cards, each with evidence
 *   that links to the exact step.
 * - **Hypotheses** were proposed (by a model, or by deterministic signatures) and cite facts.
 *   Dashed cards, labelled with who proposed them.
 * - **Recommendations** and **evidence gaps** follow.
 *
 * Nothing here is computed in the browser: every sentence is a field of the report.
 */
import { ArrowRight, CircleDashed, CircleHelp, ShieldCheck } from "lucide-react";
import Link from "next/link";
import { useCallback, useState, type ReactNode } from "react";

import { ConfidenceBadge } from "@/components/data/badges";
import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";
import type { Fact, Hypothesis, ID, Investigation, InvestigationReport, RootCause, Step } from "@/lib/api/types";
import { pluralize } from "@/lib/format";
import { cn } from "@/lib/utils";

import { EvidenceItem } from "./evidence-item";

const anchor = (kind: "fact" | "hypothesis", id: string) => `${kind}-${id}`;

/** Who proposed the hypotheses, stated truthfully from `provider` and `model`. */
export function hypothesesSource(investigation: Pick<Investigation, "provider" | "model">): string {
  return investigation.provider === "fable" ? `generated by ${investigation.model ?? "a language model"}` : "rule-based";
}

// ── Root cause ──────────────────────────────────────────────────────────────

const ROOT_CAUSE = {
  confirmed: {
    icon: ShieldCheck,
    title: "Confirmed root cause",
    frame: "border-completed/60 bg-completed/[0.07]",
    tone: "text-completed",
  },
  probable: {
    icon: CircleHelp,
    title: "Hypothesis: not confirmed",
    frame: "border-dashed border-timed-out/70",
    tone: "text-timed-out",
  },
  insufficient_evidence: {
    icon: CircleDashed,
    title: "Insufficient evidence to determine a root cause",
    frame: "border-line",
    tone: "text-fg-muted",
  },
} as const;

export function RootCauseBanner({ rootCause, source, onOpenHypothesis }: { rootCause: RootCause; source: string; onOpenHypothesis?: (id: string) => void }) {
  const look = ROOT_CAUSE[rootCause.status];
  const Icon = look.icon;
  return (
    <section aria-label="Root cause" data-root-cause={rootCause.status} className={cn("flex gap-3 rounded-lg border px-4 py-3.5", look.frame)}>
      <Icon className={cn("mt-0.5 size-5 shrink-0", look.tone)} strokeWidth={1.75} aria-hidden="true" />
      <div className="min-w-0 flex-1">
        <h2 className={cn("text-sm font-semibold", look.tone)}>{look.title}</h2>
        <p className="mt-1 max-w-4xl text-sm">{rootCause.statement}</p>
        <p className="mt-2 text-xs text-fg-muted">
          {rootCause.status === "confirmed" && (
            <>
              Confirmed by deterministic signature <code className="font-mono text-fg">{rootCause.signature}</code>. A signature is a check written in
              code against the recorded steps; no model decided this.
            </>
          )}
          {rootCause.status === "probable" && <>This is the leading hypothesis ({source}). No deterministic signature matched, so it is not confirmed.</>}
          {rootCause.status === "insufficient_evidence" && <>No deterministic signature matched and no hypothesis is supported by the facts below.</>}
          {rootCause.hypothesis_id && onOpenHypothesis && (
            <>
              {" "}
              <button
                type="button"
                onClick={() => onOpenHypothesis(rootCause.hypothesis_id!)}
                className="rounded-sm font-mono text-fg underline underline-offset-2 hover:text-fg"
              >
                See {rootCause.hypothesis_id}
              </button>
            </>
          )}
        </p>
      </div>
    </section>
  );
}

// ── Pieces ──────────────────────────────────────────────────────────────────

function SectionHeading({ id, title, qualifier, count }: { id: string; title: string; qualifier: string; count?: number }) {
  return (
    <h2 id={id} className="flex flex-wrap items-baseline gap-x-2 text-sm font-semibold">
      {/* The explicit spaces keep the heading readable as one phrase to a screen reader. */}
      {title} <span className="font-normal text-fg-muted">· {qualifier}</span>{" "}
      {count !== undefined && <span className="num font-mono text-xs font-normal text-fg-subtle">{count}</span>}
    </h2>
  );
}

/** A reference to a fact from a hypothesis: hover reads the fact, click goes to it. */
function FactChip({ fact, id, contradicts, onOpen }: { fact: Fact | undefined; id: string; contradicts?: boolean; onOpen: (id: string) => void }) {
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <button
          type="button"
          onClick={() => onOpen(id)}
          aria-label={`${contradicts ? "Contradicting" : "Supporting"} fact ${id}${fact ? `: ${fact.statement}` : ""}`}
          className={cn(
            "num rounded-sm border px-1.5 font-mono text-xs leading-5 transition-colors duration-150 hover:bg-raised",
            contradicts ? "border-failed/50 text-failed" : "border-line text-fg",
          )}
        >
          {id}
        </button>
      </TooltipTrigger>
      <TooltipContent side="top" className="max-w-sm">
        {fact ? fact.statement : "This fact is not in the report."}
      </TooltipContent>
    </Tooltip>
  );
}

function Tag({ children, className }: { children: ReactNode; className?: string }) {
  return <span className={cn("rounded-sm border border-line px-1.5 text-[11px] leading-[18px] text-fg-muted", className)}>{children}</span>;
}

function FactCard({ fact, executionId, flash }: { fact: Fact; executionId: ID; flash: boolean }) {
  return (
    <li id={anchor("fact", fact.id)} className="relative scroll-mt-4 rounded-lg border border-line bg-surface">
      {flash && <span aria-hidden="true" className="row-flash pointer-events-none absolute inset-0 rounded-lg" />}
      <div className="flex gap-3 px-4 py-3">
        <span className="num mt-px h-5 shrink-0 rounded-sm bg-fg px-1.5 font-mono text-xs font-semibold leading-5 text-background">{fact.id}</span>
        <div className="flex min-w-0 flex-1 flex-col gap-2">
          <p>{fact.statement}</p>
          <div className="grid gap-1.5 xl:grid-cols-2">
            {fact.evidence.map((item, index) => (
              <EvidenceItem key={index} evidence={item} executionId={executionId} />
            ))}
          </div>
        </div>
      </div>
    </li>
  );
}

function HypothesisCard({
  hypothesis,
  facts,
  rootCause,
  flash,
  onOpenFact,
}: {
  hypothesis: Hypothesis;
  facts: Map<string, Fact>;
  rootCause: RootCause;
  flash: boolean;
  onOpenFact: (id: string) => void;
}) {
  const isRoot = rootCause.hypothesis_id === hypothesis.id;
  return (
    <li id={anchor("hypothesis", hypothesis.id)} className="relative scroll-mt-4 rounded-lg border border-dashed border-line">
      {flash && <span aria-hidden="true" className="row-flash pointer-events-none absolute inset-0 rounded-lg" />}
      <div className="flex gap-3 px-4 py-3">
        <span className="num mt-px h-5 shrink-0 rounded-sm border border-dashed border-fg-muted px-1.5 font-mono text-xs font-semibold leading-[18px]">{hypothesis.id}</span>
        <div className="flex min-w-0 flex-1 flex-col gap-2">
          <div className="flex flex-wrap items-center gap-x-3 gap-y-1">
            <ConfidenceBadge confidence={hypothesis.confidence} className="text-xs" />
            {isRoot && rootCause.status === "confirmed" && (
              <Tag className="border-completed/50 text-completed">
                Matches signature <code className="font-mono">{rootCause.signature}</code>
              </Tag>
            )}
            {isRoot && rootCause.status === "probable" && <Tag className="border-timed-out/50 text-timed-out">Leading hypothesis</Tag>}
          </div>
          <p>{hypothesis.statement}</p>
          <p className="text-fg-muted">{hypothesis.reasoning}</p>
          <dl className="flex flex-wrap items-center gap-x-5 gap-y-1.5 text-xs">
            <div className="flex items-center gap-1.5">
              <dt className="text-fg-subtle">Supported by</dt>
              <dd className="flex flex-wrap gap-1">
                {hypothesis.supporting_fact_ids.map((id) => (
                  <FactChip key={id} id={id} fact={facts.get(id)} onOpen={onOpenFact} />
                ))}
              </dd>
            </div>
            {hypothesis.contradicting_fact_ids.length > 0 && (
              <div className="flex items-center gap-1.5">
                <dt className="text-failed">Contradicted by</dt>
                <dd className="flex flex-wrap gap-1">
                  {hypothesis.contradicting_fact_ids.map((id) => (
                    <FactChip key={id} id={id} fact={facts.get(id)} contradicts onOpen={onOpenFact} />
                  ))}
                </dd>
              </div>
            )}
          </dl>
        </div>
      </div>
    </li>
  );
}

// ── The report ──────────────────────────────────────────────────────────────

export function InvestigationReportView({
  investigation,
  report,
  steps,
}: {
  investigation: Pick<Investigation, "provider" | "model" | "execution_id">;
  report: InvestigationReport;
  /** The execution's steps, to name the steps the report refers to. Optional: ids are shown without them. */
  steps?: Step[];
}) {
  const executionId = investigation.execution_id;
  const source = hypothesesSource(investigation);
  const facts = new Map(report.facts.map((fact) => [fact.id, fact]));
  const stepById = new Map((steps ?? []).map((step) => [step.id, step]));
  const [flash, setFlash] = useState<{ target: string; at: number } | null>(null);

  const open = useCallback((kind: "fact" | "hypothesis", id: string) => {
    const target = anchor(kind, id);
    document.getElementById(target)?.scrollIntoView({ block: "center", behavior: "smooth" });
    setFlash({ target, at: Date.now() });
  }, []);
  const flashing = (kind: "fact" | "hypothesis", id: string) => flash?.target === anchor(kind, id);

  const stepLabel = (id: ID) => {
    const step = stepById.get(id);
    return step ? `Step ${step.ordinal} ${step.name}` : `${id.slice(0, 8)}…${id.slice(-4)}`;
  };

  return (
    <div className="flex flex-col gap-7">
      <RootCauseBanner rootCause={report.root_cause} source={source} onOpenHypothesis={(id) => open("hypothesis", id)} />

      <section aria-label="Summary" className="flex flex-col gap-2">
        <p className="max-w-4xl text-sm">{report.summary}</p>
        {(report.failing_step_id || report.relevant_step_ids.length > 0) && (
          <div className="flex flex-wrap items-center gap-x-4 gap-y-1 text-xs text-fg-muted">
            {report.failing_step_id && (
              <Link
                href={`/executions/${executionId}?step=${report.failing_step_id}`}
                className="inline-flex items-center gap-1 rounded-sm text-failed underline-offset-2 hover:underline"
              >
                Failing step: {stepLabel(report.failing_step_id)}
                <ArrowRight className="size-3" aria-hidden="true" />
              </Link>
            )}
            {report.relevant_step_ids
              .filter((id) => id !== report.failing_step_id)
              .map((id) => (
                <Link key={id} href={`/executions/${executionId}?step=${id}`} className="inline-flex items-center gap-1 rounded-sm underline-offset-2 hover:text-fg hover:underline">
                  {stepLabel(id)}
                  <ArrowRight className="size-3" aria-hidden="true" />
                </Link>
              ))}
          </div>
        )}
      </section>

      <section aria-labelledby="report-facts" data-section="facts" className="flex flex-col gap-2.5">
        <SectionHeading id="report-facts" title="Facts" qualifier="derived from recorded events" count={report.facts.length} />
        <p className="-mt-1 text-xs text-fg-subtle">Each fact was computed by backend code from stored data. Its evidence is copied from the record, never written by a model.</p>
        {report.facts.length === 0 ? (
          <p className="text-fg-muted">No facts could be extracted from this execution.</p>
        ) : (
          <ul className="flex flex-col gap-2">
            {report.facts.map((fact) => (
              <FactCard key={`${fact.id}:${flashing("fact", fact.id) ? flash!.at : 0}`} fact={fact} executionId={executionId} flash={flashing("fact", fact.id)} />
            ))}
          </ul>
        )}
      </section>

      <section aria-labelledby="report-hypotheses" data-section="hypotheses" className="flex flex-col gap-2.5">
        <SectionHeading id="report-hypotheses" title="Hypotheses" qualifier={source} count={report.hypotheses.length} />
        <p className="-mt-1 text-xs text-fg-subtle">
          A hypothesis is a proposed explanation, not a finding. Each one cites the facts above; a hypothesis citing a fact that does not exist is discarded
          before the report is saved.
        </p>
        {report.hypotheses.length === 0 ? (
          <p className="rounded-lg border border-dashed border-line px-4 py-3 text-fg-muted">No hypothesis is supported by the facts.</p>
        ) : (
          <ul className="flex flex-col gap-2">
            {report.hypotheses.map((hypothesis) => (
              <HypothesisCard
                key={`${hypothesis.id}:${flashing("hypothesis", hypothesis.id) ? flash!.at : 0}`}
                hypothesis={hypothesis}
                facts={facts}
                rootCause={report.root_cause}
                flash={flashing("hypothesis", hypothesis.id)}
                onOpenFact={(id) => open("fact", id)}
              />
            ))}
          </ul>
        )}
      </section>

      <section aria-labelledby="report-recommendations" data-section="recommendations" className="flex flex-col gap-2.5">
        <SectionHeading id="report-recommendations" title="Recommendations" qualifier="suggested next actions" count={report.recommendations.length} />
        {report.recommendations.length === 0 ? (
          <p className="text-fg-muted">The report makes no recommendation.</p>
        ) : (
          <ol className="flex flex-col gap-2">
            {report.recommendations.map((recommendation) => (
              <li key={recommendation.id} className="flex gap-3 rounded-lg border border-line-subtle px-4 py-3">
                <span className="num mt-px h-5 shrink-0 font-mono text-xs font-semibold leading-5 text-fg-muted">{recommendation.id}</span>
                <div className="flex min-w-0 flex-col gap-1">
                  <p className="font-medium">{recommendation.action}</p>
                  <p className="text-fg-muted">{recommendation.rationale}</p>
                  <p className="text-xs text-fg-subtle">
                    {recommendation.hypothesis_id ? (
                      <>
                        Follows from{" "}
                        <button
                          type="button"
                          onClick={() => open("hypothesis", recommendation.hypothesis_id!)}
                          className="rounded-sm font-mono text-fg-muted underline underline-offset-2 hover:text-fg"
                        >
                          {recommendation.hypothesis_id}
                        </button>
                      </>
                    ) : (
                      "Not tied to a hypothesis"
                    )}
                  </p>
                </div>
              </li>
            ))}
          </ol>
        )}
      </section>

      <section aria-labelledby="report-gaps" data-section="gaps" className="flex flex-col gap-2.5">
        <SectionHeading id="report-gaps" title="Evidence gaps" qualifier="what would make this more certain" count={report.evidence_gaps.length} />
        {report.evidence_gaps.length === 0 ? (
          <p className="text-fg-muted">None recorded.</p>
        ) : (
          <ul className="flex max-w-4xl flex-col gap-1.5">
            {report.evidence_gaps.map((gap, index) => (
              <li key={index} className="flex gap-2.5 text-fg-muted">
                <span aria-hidden="true" className="mt-2 size-1 shrink-0 rounded-full bg-fg-subtle" />
                {gap}
              </li>
            ))}
          </ul>
        )}
      </section>

      <p className="text-xs text-fg-subtle">
        {pluralize(report.facts.length, "fact")} · {pluralize(report.hypotheses.length, "hypothesis", "hypotheses")} ·{" "}
        {pluralize(report.recommendations.length, "recommendation")} · {pluralize(report.evidence_gaps.length, "evidence gap")}
      </p>
    </div>
  );
}
