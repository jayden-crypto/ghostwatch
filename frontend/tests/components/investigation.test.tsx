import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import type { ReactElement } from "react";
import { beforeEach, describe, expect, it, vi } from "vitest";

import { TooltipProvider } from "@/components/ui/tooltip";
import { createMockApi } from "@/lib/api/mock";
import type { Investigation } from "@/lib/api/types";
import { fixtures } from "@/mocks/fixtures";

const time = { now: 0 };
let mock = createMockApi({ latency: () => 0, state: () => null, clock: () => time.now });
const api = new Proxy({}, { get: (_target, method: string) => (mock as unknown as Record<string, unknown>)[method] });
vi.mock("@/lib/api/client", () => ({ api }));
const { InvestigationPanel } = await import("@/components/investigation/investigation-panel");
const { hypothesesSource, InvestigationReportView } = await import("@/components/investigation/investigation-report");

const wrap = (ui: ReactElement) =>
  render(
    <QueryClientProvider client={new QueryClient({ defaultOptions: { queries: { retry: false } } })}>
      <TooltipProvider>{ui}</TooltipProvider>
    </QueryClientProvider>,
  );

const confirmed = fixtures["investigations.get.confirmed"];
const probable = fixtures["investigations.get.probable"];
const insufficient = fixtures["investigations.get.insufficient_evidence"];
const failed = fixtures["investigations.get.failed"];
const rateLimit = fixtures["investigations.create"].execution_id;

const report = (investigation: Investigation) => wrap(<InvestigationReportView investigation={investigation} report={investigation.report!} />);
const section = (name: string) => within(screen.getByRole("region", { name: new RegExp(`^${name}`) }));

beforeEach(() => {
  time.now = 0;
  mock = createMockApi({ latency: () => 0, state: () => null, clock: () => time.now });
});

describe("root cause", () => {
  it("confirmed: names the deterministic signature and says no model decided it", () => {
    report(confirmed);
    const banner = screen.getByRole("region", { name: "Root cause" });
    expect(banner).toHaveAttribute("data-root-cause", "confirmed");
    expect(within(banner).getByRole("heading", { name: "Confirmed root cause" })).toBeInTheDocument();
    expect(within(banner).getByText("missing_key_in_upstream_output")).toBeInTheDocument();
    expect(banner).toHaveTextContent("no model decided this");
    expect(within(banner).getByText(confirmed.report!.root_cause.statement)).toBeInTheDocument();
  });

  it("probable: is labelled a hypothesis, not confirmed, with who proposed it", () => {
    report(probable);
    const banner = screen.getByRole("region", { name: "Root cause" });
    expect(banner).toHaveAttribute("data-root-cause", "probable");
    expect(within(banner).getByRole("heading", { name: "Hypothesis: not confirmed" })).toBeInTheDocument();
    expect(banner).toHaveTextContent("generated by claude-fable-5-2");
    expect(banner).toHaveTextContent("No deterministic signature matched");
    expect(banner).not.toHaveTextContent(/Confirmed root cause/);
  });

  it("insufficient evidence: says so plainly and offers no hypothesis", () => {
    report(insufficient);
    const banner = screen.getByRole("region", { name: "Root cause" });
    expect(banner).toHaveAttribute("data-root-cause", "insufficient_evidence");
    expect(within(banner).getByRole("heading", { name: "Insufficient evidence to determine a root cause" })).toBeInTheDocument();
    expect(section("Hypotheses").getByText("No hypothesis is supported by the facts.")).toBeInTheDocument();
    expect(section("Recommendations").getByText("The report makes no recommendation.")).toBeInTheDocument();
  });

  it("gives the three states three different looks", () => {
    const looks = [confirmed, probable, insufficient].map((investigation) => {
      const { unmount } = report(investigation);
      const className = screen.getByRole("region", { name: "Root cause" }).className;
      unmount();
      return className;
    });
    expect(new Set(looks).size).toBe(3);
    expect(looks[1]).toContain("border-dashed");
    expect(looks[0]).not.toContain("border-dashed");
  });
});

describe("facts and hypotheses", () => {
  it("labels facts as derived from recorded events and hypotheses with their true source", () => {
    report(probable);
    expect(screen.getByRole("heading", { name: /^Facts · derived from recorded events/ })).toBeInTheDocument();
    expect(screen.getByRole("heading", { name: /^Hypotheses · generated by claude-fable-5-2/ })).toBeInTheDocument();
    expect(hypothesesSource({ provider: "rule_based", model: null })).toBe("rule-based");
    expect(hypothesesSource({ provider: "fable", model: "claude-fable-5-2" })).toBe("generated by claude-fable-5-2");
  });

  it("says rule-based when no model was used", () => {
    report(confirmed);
    expect(screen.getByRole("heading", { name: /^Hypotheses · rule-based/ })).toBeInTheDocument();
    expect(section("Hypotheses").getByText(/Matches signature/)).toBeInTheDocument();
  });

  it("shows every fact with its evidence, and links step evidence to the exact step", () => {
    report(confirmed);
    const facts = section("Facts");
    for (const fact of confirmed.report!.facts) expect(facts.getByText(fact.statement)).toBeInTheDocument();
    const stepLinks = facts.getAllByRole("link", { name: "Open step" });
    const failing = confirmed.report!.failing_step_id;
    expect(stepLinks.some((link) => link.getAttribute("href") === `/executions/${confirmed.execution_id}?step=${failing}`)).toBe(true);
    // observed and expected are shown verbatim.
    expect(facts.getByText('["web_search","parse_results","summarize"]')).toBeInTheDocument();
  });

  it("shows supporting and contradicting facts, a text confidence level, and jumps to a cited fact", async () => {
    const user = userEvent.setup();
    report(probable);
    const hypotheses = section("Hypotheses");
    expect(hypotheses.getByText("Medium confidence")).toBeInTheDocument();
    expect(hypotheses.getByText("Low confidence")).toBeInTheDocument();
    expect(hypotheses.queryByText(/%/)).not.toBeInTheDocument();
    const contradicted = probable.report!.hypotheses[1].contradicting_fact_ids[0];
    const chip = hypotheses.getByRole("button", { name: new RegExp(`^Contradicting fact ${contradicted}:`) });
    expect(hypotheses.getByText("Contradicted by")).toBeInTheDocument();
    await user.click(chip);
    const target = document.getElementById(`fact-${contradicted}`)!;
    expect(target.querySelector(".row-flash")).not.toBeNull();
  });

  it("lists recommendations with the hypothesis they follow from, and the evidence gaps", () => {
    report(probable);
    const recommendations = section("Recommendations");
    for (const recommendation of probable.report!.recommendations) expect(recommendations.getByText(recommendation.action)).toBeInTheDocument();
    expect(recommendations.getByRole("button", { name: "H1" })).toBeInTheDocument();
    expect(recommendations.getByText("Not tied to a hypothesis")).toBeInTheDocument();
    const gaps = section("Evidence gaps");
    for (const gap of probable.report!.evidence_gaps) expect(gaps.getByText(gap)).toBeInTheDocument();
  });

  it("says when a report has no evidence gaps", () => {
    report(confirmed);
    expect(section("Evidence gaps").getByText("None recorded.")).toBeInTheDocument();
  });
});

describe("investigation states", () => {
  it("offers to investigate a run that has not been investigated, then polls to the report", { timeout: 15_000 }, async () => {
    const user = userEvent.setup();
    wrap(<InvestigationPanel executionId={rateLimit} />);
    expect(await screen.findByText("This execution has not been investigated")).toBeInTheDocument();
    await user.click(screen.getByRole("button", { name: "Investigate" }));
    expect(await within(await screen.findByRole("status")).findByText("Queued")).toBeInTheDocument();
    // The view polls every 2 s; each state appears on the poll after the mock's clock passes it.
    time.now = 2_000;
    await waitFor(() => expect(within(screen.getByRole("status")).getByText("Investigating")).toBeInTheDocument(), { timeout: 4_000 });
    time.now = 5_000;
    expect(await screen.findByRole("region", { name: "Root cause" }, { timeout: 4_000 })).toHaveAttribute("data-root-cause", "insufficient_evidence");
    expect(screen.getByText("Manual")).toBeInTheDocument();
  });

  it("shows the API's refusal when an investigation cannot be started", async () => {
    const user = userEvent.setup();
    wrap(<InvestigationPanel executionId={fixtures["executions.get.running"].id} />);
    await user.click(await screen.findByRole("button", { name: "Investigate" }));
    expect(await screen.findByRole("alert")).toHaveTextContent("An investigation cannot be started while the execution is still running.");
  });

  it("shows a failed investigation as a failure of the investigation, with a way to retry", async () => {
    const user = userEvent.setup();
    wrap(<InvestigationPanel executionId={failed.execution_id} />);
    const alert = await screen.findByRole("alert");
    expect(alert).toHaveTextContent("The investigation failed");
    expect(alert).toHaveTextContent(failed.error!.message);
    expect(alert).toHaveTextContent("not a finding about the execution");
    await user.click(screen.getByRole("button", { name: "Run again" }));
    await waitFor(() => expect(within(screen.getByRole("status")).getByText("Queued")).toBeInTheDocument());
  });

  it("shows an existing report with its status, trigger and provider", async () => {
    wrap(<InvestigationPanel executionId={confirmed.execution_id} />);
    expect(await screen.findByRole("region", { name: "Root cause" })).toHaveAttribute("data-root-cause", "confirmed");
    expect(screen.getByText("Auto · failure")).toBeInTheDocument();
    expect(screen.getByText("Rule-based")).toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Run again" })).toBeInTheDocument();
  });
});
