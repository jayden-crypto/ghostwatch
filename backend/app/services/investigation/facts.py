"""Facts: what the stored events prove, stated by code.

Every fact is a template filled from stored rows, with evidence that points at the row and copies
its values. Nothing here is generated by a model. Hypotheses may only cite these facts.
"""

import re
from dataclasses import dataclass, field
from typing import Any

from app.models import Step
from app.services.anomaly import thresholds
from app.services.evidence import evidence_item, json_excerpt
from app.services.executions import tokens_total
from app.services.investigation.context import InvestigationContext

PRECEDING_STEPS = 3
MAX_EVIDENCE_PER_FACT = 10
_HTTP_STATUS_KEYS = ("status", "status_code", "http_status")
# "HTTP 503", "HTTPError 429 ..." or "status code: 404". Deliberately strict: a number that merely
# appears near the word HTTP ("HTTP timeout after 500 ms") must not be read as a status.
_HTTP_IN_TEXT = re.compile(r"(?:HTTP\w*|\bstatus(?:[ _]code)?)\D{0,3}([45]\d\d)\b", re.IGNORECASE)


@dataclass
class FactSet:
    facts: list[dict[str, Any]] = field(default_factory=list)  # contract Fact objects
    ids: dict[str, str] = field(default_factory=dict)  # internal key -> fact id, for the signatures
    gaps: list[str] = field(default_factory=list)
    failing_step: Step | None = None
    http_statuses: dict[str, int] = field(default_factory=dict)  # step id -> HTTP status >= 400

    def add(self, key: str, statement: str, evidence: list[dict[str, Any]]) -> None:
        fact_id = f"F{len(self.facts) + 1}"
        self.facts.append(
            {"id": fact_id, "statement": statement, "evidence": evidence[:MAX_EVIDENCE_PER_FACT]}
        )
        self.ids[key] = fact_id

    def cite(self, *keys: str) -> list[str]:
        """Ids of the facts with these keys, skipping any that were not extracted."""
        return [self.ids[key] for key in keys if key in self.ids]


def step_label(step: Step) -> str:
    attempt = f" (attempt {step.attempt})" if step.attempt > 1 else ""
    return f"Step {step.ordinal} {step.name}{attempt}"


def error_text(error: dict[str, Any] | None) -> str:
    return f"{error['type']}: {error['message']}" if error else "no error recorded"


def find_failing_step(context: InvestigationContext) -> Step | None:
    """The step the failure belongs to.

    Failed execution: the last failed step that carries the execution's own error (the step the
    exception escaped from), else the last failed step. Timed-out execution: the last step that was
    still running. A completed execution has no failing step.
    """
    execution, steps = context.execution, context.steps
    if execution.status == "failed":
        failed = [step for step in steps if step.status == "failed"]
        error = execution.error or {}
        same_error = [
            step
            for step in failed
            if step.error
            and (step.error.get("type"), step.error.get("message"))
            == (error.get("type"), error.get("message"))
        ]
        candidates = same_error or failed
        return candidates[-1] if candidates else None
    if execution.status == "timed_out":
        running = [step for step in steps if step.status == "running"]
        return running[-1] if running else None
    return None


def http_status_of(step: Step) -> int | None:
    """An HTTP status >= 400 that a tool step reported in its output or its error, if any."""
    if not step.tool_name:
        return None
    if isinstance(step.output, dict):
        for key in _HTTP_STATUS_KEYS:
            value = step.output.get(key)
            if isinstance(value, int) and not isinstance(value, bool) and 400 <= value <= 599:
                return value
    if step.error:
        match = _HTTP_IN_TEXT.search(f"{step.error.get('type', '')} {step.error.get('message', '')}")
        if match:
            return int(match.group(1))
    return None


def _describe_output(output: Any) -> tuple[str, Any]:
    """(what the output is, in words; the observed value for the evidence item)."""
    if output is None:
        return "has no output", None
    if isinstance(output, dict) and output.get("_truncated") is True:
        size = output.get("original_bytes")
        return (
            f"has an output that was truncated at ingestion ({size} bytes; only a preview is stored)",
            output,
        )
    if isinstance(output, dict):
        keys = sorted(output)
        return f"returned an object with keys: {', '.join(keys) if keys else '(none)'}", keys
    if isinstance(output, list):
        return f"returned a list of {len(output)} items", {"type": "list", "length": len(output)}
    return f"returned a {type(output).__name__} value", output


def build_facts(context: InvestigationContext) -> FactSet:
    execution, steps = context.execution, context.steps
    facts = FactSet(failing_step=find_failing_step(context))
    failing = facts.failing_step

    facts.add(
        "outcome",
        f"Execution of {context.agent_slug} ended with status {execution.status} after "
        f"{execution.duration_ms} ms and {execution.step_count} steps.",
        [
            evidence_item(
                "execution",
                "Final status of the execution",
                ref_id=execution.id,
                field="status",
                observed=execution.status,
            )
        ],
    )
    if execution.error:
        facts.add(
            "execution_error",
            f"The execution ended with the error {error_text(execution.error)}.",
            [
                evidence_item(
                    "execution",
                    "Terminal error of the execution",
                    ref_id=execution.id,
                    field="error.message",
                    observed=execution.error.get("message"),
                    excerpt=execution.error.get("message"),
                )
            ],
        )

    if failing is not None and failing.status == "failed":
        evidence = [
            evidence_item(
                "step",
                f"Error raised in {step_label(failing)}",
                ref_id=failing.id,
                field="error.message",
                observed=failing.error.get("message"),
                excerpt=failing.error.get("message"),
            )
        ]
        stacktrace = failing.error.get("stacktrace")
        if stacktrace:
            evidence.append(
                evidence_item(
                    "step",
                    f"End of the stack trace of {step_label(failing)}",
                    ref_id=failing.id,
                    field="error.stacktrace",
                    observed=failing.error.get("type"),
                    excerpt=stacktrace[-500:],
                )
            )
        facts.add("failing_step", f"{step_label(failing)} failed with {error_text(failing.error)}.", evidence)
    elif failing is not None:
        facts.add(
            "failing_step",
            f"{step_label(failing)} had started and was still running when the execution timed out.",
            [
                evidence_item(
                    "step",
                    f"Status of {step_label(failing)}",
                    ref_id=failing.id,
                    field="status",
                    observed="running",
                )
            ],
        )

    # Outputs just before the failure (or before the end), plus the nearest tool output further back.
    anchor = failing.ordinal if failing is not None else execution.step_count + 1
    before = [step for step in steps if step.ordinal < anchor]
    window = before[-PRECEDING_STEPS:]
    nearest_tool = next(
        (step for step in reversed(before) if step.tool_name and step.status == "completed"), None
    )
    if nearest_tool is not None and nearest_tool not in window:
        window = [nearest_tool, *window]
    for step in window:
        description, observed = _describe_output(step.output)
        facts.add(
            f"output:{step.id}",
            f"{step_label(step)} ({step.type}, {step.status}) {description}.",
            [
                evidence_item(
                    "step",
                    f"Output of {step_label(step)}",
                    ref_id=step.id,
                    field="output",
                    observed=observed,
                    excerpt=None if step.output is None else json_excerpt(step.output),
                )
            ],
        )

    names_with_retries = list(dict.fromkeys(step.name for step in steps if step.attempt > 1))
    for name in names_with_retries:
        attempts = [step for step in steps if step.name == name]
        history = ", ".join(
            f"attempt {step.attempt} {step.status}" + (f" ({step.error['type']})" if step.error else "")
            for step in attempts
        )
        facts.add(
            f"retry:{name}",
            f"{name} was attempted {len(attempts)} times: {history}.",
            [
                evidence_item(
                    "step",
                    f"{step_label(step)}: {step.status}",
                    ref_id=step.id,
                    field="error.message" if step.error else "status",
                    observed=step.error.get("message") if step.error else step.status,
                    excerpt=step.error.get("message") if step.error else None,
                )
                for step in attempts
            ],
        )

    for step in steps:
        status = http_status_of(step)
        if status is not None:
            facts.http_statuses[step.id] = status
            source = (
                "output"
                if isinstance(step.output, dict)
                and any(step.output.get(key) == status for key in _HTTP_STATUS_KEYS)
                else "error.message"
            )
            facts.add(
                f"http:{step.id}",
                f"{step_label(step)} (tool {step.tool_name}) reported HTTP status {status}.",
                [
                    evidence_item(
                        "step",
                        f"HTTP status reported by {step_label(step)}",
                        ref_id=step.id,
                        field=source,
                        observed=status,
                        expected="below 400",
                        excerpt=step.error.get("message")
                        if source == "error.message"
                        else json_excerpt(step.output),
                    )
                ],
            )

    running = [step for step in steps if step.status == "running" and step is not failing]
    if running:
        facts.add(
            "running_steps",
            f"{len(running)} step(s) were still running when the execution ended: "
            f"{', '.join(step_label(step) for step in running)}.",
            [
                evidence_item(
                    "step",
                    f"Status of {step_label(step)}",
                    ref_id=step.id,
                    field="status",
                    observed="running",
                )
                for step in running
            ],
        )

    expected_steps = execution.config.get("expected_steps") or []
    if expected_steps:
        completed = list(dict.fromkeys(step.name for step in steps if step.status == "completed"))
        missing = [name for name in dict.fromkeys(expected_steps) if name not in completed]
        facts.add(
            "expected_steps",
            f"The execution is configured to expect these steps to complete: {', '.join(expected_steps)}. "
            f"Steps that completed: {', '.join(completed) or 'none'}. "
            f"Expected steps that did not complete: {', '.join(missing) or 'none'}.",
            [
                evidence_item(
                    "execution",
                    "Expected steps compared with completed steps",
                    ref_id=execution.id,
                    field="config.expected_steps",
                    observed=completed,
                    expected=expected_steps,
                )
            ],
        )

    for anomaly in context.anomalies:
        facts.add(
            f"anomaly:{anomaly.type}",
            f"Anomaly {anomaly.type} ({anomaly.severity}) was raised on this execution: {anomaly.title}.",
            [
                evidence_item(
                    "anomaly",
                    f"Why rule {anomaly.rule_id} fired",
                    ref_id=anomaly.id,
                    field="explanation",
                    observed=anomaly.title,
                    excerpt=anomaly.explanation,
                ),
                *anomaly.evidence,
            ],
        )

    baseline = context.baseline
    if baseline.is_sufficient:
        tokens = tokens_total(execution)
        facts.add(
            "baseline",
            f"This execution took {execution.duration_ms} ms over {execution.step_count} steps. Over the "
            f"last {baseline.runs} completed runs of {context.agent_slug}, the median duration is "
            f"{baseline.duration_median:g} ms (p95 {baseline.duration_p95} ms) and the largest step count is "
            f"{baseline.max_step_count}.",
            [
                evidence_item(
                    "baseline",
                    f"This execution compared with {baseline.runs} completed runs",
                    observed={
                        "duration_ms": execution.duration_ms,
                        "step_count": execution.step_count,
                        "tokens_total": tokens,
                    },
                    expected={
                        "median_duration_ms": baseline.duration_median,
                        "p95_duration_ms": baseline.duration_p95,
                        "max_step_count": baseline.max_step_count,
                        "median_tokens_total": baseline.token_median if baseline.has_token_baseline else None,
                    },
                )
            ],
        )
    else:
        facts.gaps.append(
            f"Only {baseline.runs} completed baseline run(s) exist for {context.agent_slug}; at least "
            f"{thresholds.MIN_BASELINE_RUNS} are needed to compare this execution with normal behaviour."
        )

    if execution.status == "failed" and failing is None:
        facts.gaps.append("No step recorded the failure, so it happened outside any instrumented step.")
    if any(isinstance(step.output, dict) and step.output.get("_truncated") is True for step in steps):
        facts.gaps.append("At least one step output was larger than 64 KB and is stored only as a preview.")
    return facts
